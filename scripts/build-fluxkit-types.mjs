#!/usr/bin/env node
// Generates src/packages/builtin-fluxkit.ts: fluxkit's declaration files, as
// the node_modules/fluxkit/ the playground hands to tsrs, so that
// `import * as fx from 'fluxkit'` type checks without fetching anything.
//
//   node scripts/build-fluxkit-types.mjs          writes the module
//   node scripts/build-fluxkit-types.mjs --check  fails if it is stale
//
// The declarations come from TypeScript's own emit over packages/fluxkit/src.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const outFile = path.join(root, 'src/packages/builtin-fluxkit.ts');

/** The generated module's source. */
export function build() {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'fluxkit-dts-'));
  try {
    execFileSync(
      process.execPath,
      [path.join(root, 'node_modules/typescript/bin/tsc'), '-p', path.join(root, 'packages/fluxkit/tsconfig.json'), '--outDir', out],
      { stdio: 'pipe' }
    );
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'packages/fluxkit/package.json'), 'utf8'));
    const files = {
      'node_modules/fluxkit/package.json': `${JSON.stringify({ name: 'fluxkit', version: pkg.version, types: 'index.d.ts' }, null, 2)}\n`,
    };
    for (const name of fs.readdirSync(out).filter((f) => f.endsWith('.d.ts')).sort()) {
      const text = fs.readFileSync(path.join(out, name), 'utf8')
        // './model.ts' -> './model.js', which resolves to model.d.ts.
        .replace(/(from\s+['"]\.{1,2}\/[^'"]+)\.ts(['"])/g, '$1.js$2');
      files[`node_modules/fluxkit/${name}`] = text;
    }
    return `// Generated by scripts/build-fluxkit-types.mjs from packages/fluxkit/src. Do not edit.
// fluxkit's declaration files, handed to tsrs as node_modules/fluxkit/.

export const FLUXKIT_VERSION = ${JSON.stringify(pkg.version)};

export const FLUXKIT_TYPES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;
  } finally {
    fs.rmSync(out, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = build();
  if (process.argv[2] === '--check') {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (current !== source) {
      console.error(`${path.relative(root, outFile)} is stale: run node scripts/build-fluxkit-types.mjs`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(outFile, source);
    console.log(`Wrote ${path.relative(root, outFile)}`);
  }
}
