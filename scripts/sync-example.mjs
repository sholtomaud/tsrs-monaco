#!/usr/bin/env node
// Bundles an example project kept as real files under examples/<name>/ into
// src/examples/<name>.ts, the module the playground loads:
//
//   node scripts/sync-example.mjs energy-flows          writes the module
//   node scripts/sync-example.mjs energy-flows --check  fails if it is stale
//
// Every file under examples/<name>/ becomes a project file at the same
// relative path. The playground adds its default tsconfig.json (unless the
// example has its own) and src/playground.d.ts, which declares plot(),
// test() and expect().

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const rank = (file) =>
  file === 'src/index.ts' ? 0 : file.endsWith('.ts') && !/\.(test|d)\.ts$/.test(file) ? 1 : 2;

/** The generated module's source for examples/<name>/. */
export function bundle(name) {
  const dir = path.join(root, 'examples', name);
  const files = walk(dir)
    .map((file) => path.relative(dir, file).split(path.sep).join('/'))
    .filter((file) => file !== 'src/playground.d.ts')
    // Tabs: the entry, then modules, then tests and everything else.
    .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  const entries = files.map(
    (file) => `  ${JSON.stringify(file)}: ${JSON.stringify(fs.readFileSync(path.join(dir, file), 'utf8'))},`
  );
  const tsconfig = files.includes('tsconfig.json') ? [] : ['  [TSCONFIG]: DEFAULT_TSCONFIG,'];
  return `// Generated by scripts/sync-example.mjs from examples/${name}/. Do not edit:
// change the files there and run \`node scripts/sync-example.mjs ${name}\`.

import { DEFAULT_TSCONFIG, TSCONFIG, type ProjectFiles } from '../compiler/project.ts';
import { PLAYGROUND_DTS } from './playground-dts.ts';

export const files: ProjectFiles = {
${[...tsconfig, ...entries, "  'src/playground.d.ts': PLAYGROUND_DTS,"].join('\n')}
};
`;
}

export const outputFor = (name) => path.join(root, 'src/examples', `${name}.ts`);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [name, flag] = process.argv.slice(2);
  if (!name || !fs.existsSync(path.join(root, 'examples', name))) {
    console.error('Usage: node scripts/sync-example.mjs <name under examples/> [--check]');
    process.exit(1);
  }
  const out = outputFor(name);
  const source = bundle(name);
  if (flag === '--check') {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (current !== source) {
      console.error(`${path.relative(root, out)} is stale: run node scripts/sync-example.mjs ${name}`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(out, source);
    console.log(`Wrote ${path.relative(root, out)}`);
  }
}
