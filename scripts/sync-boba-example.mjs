#!/usr/bin/env node
// Regenerates src/examples/boba-app.ts from a checkout of Boba's app template
// (https://github.com/sholtomaud/boba/tree/main/template):
//
//   node scripts/sync-boba-example.mjs [path/to/boba/template]
//
// The example keeps the template's index.html, public/ and src/ as they are,
// minus its node:test files (the playground has its own test()). Two files
// are the playground's own: a tsconfig.json for tsrs, and a vite-env.d.ts
// declaring the Vite features (`?raw` and CSS imports) that the Preview tab
// provides instead of Vite.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const templateDir = path.resolve(process.argv[2] ?? path.join(root, '../boba/template'));
const outFile = path.join(root, 'src/examples/boba-app.ts');

const TSCONFIG = `{
  "compilerOptions": {
    "target": "es2022",
    "module": "esnext",
    "moduleResolution": "bundler",
    // A web app: it runs in the Preview tab's page, so the DOM is available.
    "lib": ["esnext", "dom"],
    "strict": true,
    "skipLibCheck": true,
    "allowImportingTsExtensions": true,
    "rewriteRelativeImportExtensions": true,
    "rootDir": "src",
    "outDir": "dist"
  },
  "include": ["src"]
}
`;

const VITE_ENV = `// Boba is built with Vite. The playground's Preview tab provides the two
// Vite features the template uses, so declare them for the type checker.

/** \`import text from './file.html?raw'\`: the file's contents as a string. */
declare module '*?raw' {
  const content: string;
  export default content;
}

/** \`import './styles.css'\`: adds the stylesheet to the page. */
declare module '*.css';
`;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

if (!fs.existsSync(path.join(templateDir, 'index.html'))) {
  console.error(`No Boba template at ${templateDir}`);
  process.exit(1);
}

const files = { 'tsconfig.json': TSCONFIG };
const sources = ['index.html', ...['public', 'src'].flatMap((dir) =>
  walk(path.join(templateDir, dir)).map((file) => path.relative(templateDir, file))
)]
  .map((file) => file.split(path.sep).join('/'))
  .filter((file) => !file.endsWith('.test.ts'))
  .sort();
for (const file of sources) {
  files[file] = file === 'src/vite-env.d.ts'
    ? VITE_ENV
    : fs.readFileSync(path.join(templateDir, file), 'utf8');
}
files['src/vite-env.d.ts'] ??= VITE_ENV;

const body = Object.entries(files)
  .map(([file, text]) => `  ${JSON.stringify(file)}: ${JSON.stringify(text)},`)
  .join('\n');

fs.writeFileSync(
  outFile,
  `// Generated by scripts/sync-boba-example.mjs from Boba's app template. Do not edit.

import type { ProjectFiles } from '../compiler/project.ts';

export const files: ProjectFiles = {
${body}
};
`
);
console.log(`Wrote ${path.relative(root, outFile)} (${Object.keys(files).length} files)`);
